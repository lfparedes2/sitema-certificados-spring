CREATE SCHEMA IF NOT EXISTS seguridad;

CREATE TABLE IF NOT EXISTS seguridad.aplicacion (
    id_aplicacion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aplicacion_descripcion character varying(200),
    aplicacion_nombre_codigo character varying(100) NOT NULL,
    aplicacion_nombre_visible character varying(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS seguridad.email_evento (
    id_mail_evento integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    codigo character varying(32) NOT NULL,
    descripcion character varying(200),
    asunto character varying(200) NOT NULL,
    email_remitente character varying(100),
    estado character varying(1) NOT NULL,
    plantilla text,
    CONSTRAINT ckc_estado_men_even CHECK (estado IN ('A', 'I'))
);

CREATE TABLE IF NOT EXISTS seguridad.menu (
    id_menu bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_accion character varying(100),
    menu_estado character varying(50) NOT NULL,
    menu_etiqueta character varying(100),
    menu_img character varying(1000),
    menu_nivel integer,
    menu_orden integer,
    menu_tipo character varying(50) NOT NULL,
    id_aplicacion bigint NOT NULL,
    menu_id_padre bigint,
    CONSTRAINT fk_menu_aplicacion FOREIGN KEY (id_aplicacion) REFERENCES seguridad.aplicacion(id_aplicacion),
    CONSTRAINT fk_menu_padre FOREIGN KEY (menu_id_padre) REFERENCES seguridad.menu(id_menu)
);

CREATE TABLE IF NOT EXISTS seguridad.rol (
    id_rol bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_descripcion character varying(200),
    rol_nombre_codigo character varying(100) NOT NULL,
    rol_nombre_visible character varying(150) NOT NULL,
    id_aplicacion bigint NOT NULL,
    CONSTRAINT fk_rol_aplicacion FOREIGN KEY (id_aplicacion) REFERENCES seguridad.aplicacion(id_aplicacion)
);

CREATE TABLE IF NOT EXISTS seguridad.rol_menu (
    id_rol_menu bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_menu bigint NOT NULL,
    id_rol bigint NOT NULL,
    CONSTRAINT fk_rol_menu_menu FOREIGN KEY (id_menu) REFERENCES seguridad.menu(id_menu),
    CONSTRAINT fk_rol_menu_rol FOREIGN KEY (id_rol) REFERENCES seguridad.rol(id_rol)
);

CREATE TABLE IF NOT EXISTS seguridad.usuario (
    id_usuario bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_caducida_pasaporte date,
    id_funcionario integer,
    inicial character varying(3),
    tipo_identificacion character varying(2),
    usuario_cedula character varying(15) CONSTRAINT uk_ceduka UNIQUE,
    usuario_contrasenia character varying(300),
    usuario_email character varying(50) NOT NULL,
    usuario_estado character varying(50) NOT NULL,
    usuario_nombre character varying(100),
    usuario_tipo character varying(50) NOT NULL,
    usuario_username character varying(50) NOT NULL,
    fecha_creacion date,
    fecha_caduca_pasword timestamp with time zone,
    code_verifica integer
);

CREATE TABLE IF NOT EXISTS seguridad.usuario_rol (
    id_usuario_rol bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_rol_estado character varying(50) NOT NULL,
    id_rol bigint NOT NULL,
    id_usuario bigint NOT NULL,
    CONSTRAINT fk_usuario_rol_rol FOREIGN KEY (id_rol) REFERENCES seguridad.rol(id_rol),
    CONSTRAINT fk_usuario_rol_usuario FOREIGN KEY (id_usuario) REFERENCES seguridad.usuario(id_usuario)
);
